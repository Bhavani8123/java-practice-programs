public class javaOp5 {

    public static void main(String[] args) {

        int age = 22;
        boolean hasId = true;

        // AND
        System.out.println(age >= 18 && hasId == true);

        // OR
        System.out.println(age >= 18 || hasId == false);

        // NOT
        System.out.println(!hasId);
    }
}
